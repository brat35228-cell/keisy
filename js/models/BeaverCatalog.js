import { Money } from "../core/Money.js";

/** Окрема драбина кейсів вкладки «Бобри»: кожен наступний у п'ять разів дорожчий. */
export class BeaverCatalog {
  static RANK_MULT = [0.38, 0.45, 0.52, 0.6, 0.68, 0.76, 0.85, 0.95, 1.1, 1.25, 1.45, 1.7, 2.1, 2.6, 3.2, 3.8, 5.2, 7, 9, 16];
  static RANKS = [
    "Уламок", "Осколок", "Шматок", "Звичайний", "Міцний", "Гарний", "Якісний", "Рідкісний",
    "Добірний", "Відбірний", "Цінний", "Дорогий", "Блискучий", "Коштовний", "Королівський",
    "Імперський", "Епічний", "Міфічний", "Легендарний", "Абсолютний",
  ];
  static NAMES = [
    ["Гілочки", "🌿"], ["Кора", "🪵"], ["Корчі", "🌲"], ["Пеньки", "🌳"], ["Хатки", "🏠"],
    ["Греблі", "🏗️"], ["Струмки", "💧"], ["Річки", "🌊"], ["Озера", "🏞️"], ["Болота", "🐸"],
    ["Норки", "🕳️"], ["Затоки", "🛶"], ["Канали", "🌉"], ["Водоспади", "⛲"], ["Ліси", "🌲"],
    ["Галявини", "🌼"], ["Бобри", "🦫"], ["Бобрята", "🐾"], ["Зуби", "🦷"], ["Хвости", "🎗️"],
    ["Лапи", "🐾"], ["Шубки", "🧥"], ["Риби", "🐟"], ["Жабки", "🐸"], ["Качки", "🦆"],
    ["Видри", "🦦"], ["Ягоди", "🫐"], ["Шишки", "🌰"], ["Мох", "🌿"], ["Камені", "🪨"],
    ["Мушлі", "🐚"], ["Перлини", "🤍"], ["Пісок", "⏳"], ["Бурштин", "🟠"], ["Скарби", "💎"],
    ["Корони", "👑"], ["Тотеми", "🗿"], ["Руни", "🔮"], ["Місяць", "🌙"], ["Зорі", "⭐"],
    ["Крига", "❄️"], ["Вулкан", "🌋"], ["Небо", "☁️"], ["Космос", "🚀"], ["Галактики", "🌀"],
    ["Квант", "⚛️"], ["Міф", "🐉"], ["Боги", "🔱"], ["Мультирічка", "♾️"], ["Безодня", "🕳️"],
  ];

  #cases;

  constructor() {
    this.#cases = BeaverCatalog.NAMES.map((pair, index) => {
      const price = Money.round(10 * Math.pow(5, index));
      return {
        id: "b" + index,
        n: pair[0],
        e: pair[1],
        p: price,
        b: price,
        items: BeaverCatalog.RANKS.map((rank, slot) => ({
          e: pair[1],
          n: rank + " · " + pair[0],
          v: Money.round(price * BeaverCatalog.RANK_MULT[slot]),
        })),
      };
    });
  }

  get cases() {
    return this.#cases;
  }

  find(id) {
    return this.#cases.find((entry) => entry.id === id);
  }
}
